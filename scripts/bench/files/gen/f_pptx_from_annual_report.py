def _typo(text: str) -> str:
    """Russian typography: no-break space inside thousands («3 135») and before «%»."""
    text = re.sub(r"(?<=\d) (?=\d{3}(?!\d))", "\u00a0", text)
    return re.sub(r"(?<=\d) %", "\u00a0%", text)


def _word_count():
    texts = []
    for kind, payload in CONTENT:
        if isinstance(payload, str):
            texts.append(payload)
        elif isinstance(payload, list):
            texts.extend(payload)
    return len(re.findall(r"\w+", " ".join(texts)))


