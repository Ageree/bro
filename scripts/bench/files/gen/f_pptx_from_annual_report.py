def _shade(cell, hex_fill):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tcpr.append(shd)


def _table(doc, caption, head, rows, total=None, widths=None):
    cap = doc.add_paragraph()
    cap.paragraph_format.keep_with_next = True
    cap.paragraph_format.space_before = Pt(6)
    cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = cap.add_run(caption)
    r.bold = True
    r.font.size = Pt(11)
    t = doc.add_table(rows=1 + len(rows) + (1 if total else 0), cols=len(head))
    t.style = doc.styles["Table Grid"]
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    if widths:
        t.autofit = False
        for gc, wcm in zip(t._tbl.tblGrid.findall(qn("w:gridCol")), widths):
            gc.set(qn("w:w"), str(int(round(wcm / 2.54 * 1440))))
    all_rows = [head] + rows + ([total] if total else [])
    for ri, vals in enumerate(all_rows):
        for ci, v in enumerate(vals):
            cell = t.cell(ri, ci)
            if widths:
                cell.width = Cm(widths[ci])
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.first_line_indent = Cm(0)
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if ci == 0 else WD_ALIGN_PARAGRAPH.RIGHT
            run = p.add_run(_typo(v))
            run.font.size = Pt(11)
            if ri == 0 or (total and ri == len(all_rows) - 1):
                run.bold = True
            if ri == 0:
                _shade(cell, "DCEFE6")
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            if ri < len(all_rows) - 1:
                p.paragraph_format.keep_with_next = True
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


