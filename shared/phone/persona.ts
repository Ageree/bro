const tens = [
  "",
  "",
  "двадцать",
  "тридцать",
  "сорок",
  "пятьдесят",
  "шестьдесят",
  "семьдесят",
  "восемьдесят",
  "девяносто",
];
const hundreds = [
  "",
  "сто",
  "двести",
  "триста",
  "четыреста",
  "пятьсот",
  "шестьсот",
  "семьсот",
  "восемьсот",
  "девятьсот",
];

function groupWords(group: string) {
  // «05» and «007» are read digit by digit, as people dictate them.
  if (group.startsWith("0"))
    return group
      .split("")
      .map((digit) => units[Number(digit)])
      .join(" ");
  const value = Number(group);
  const words = [hundreds[Math.floor(value / 100)]];
  const rest = value % 100;
  if (rest >= 10 && rest < 20) words.push(teens[rest - 10]);
  else {
    words.push(tens[Math.floor(rest / 10)]);
    if (rest % 10 || value === 0) words.push(units[rest % 10]);
  }
  return words.filter(Boolean).join(" ");
}

/**
 * +79249098921 as it is dictated: «плюс семь, девятьсот двадцать четыре, девятьсот девять, восемьдесят девять,
 * двадцать один». GPT-Live read the digits itself and swapped a group (18.10: «…восемьдесят девять» for «…двадцать один»).
 */
export function spokenPhone(number: string) {
  const digits = number.replace(/\D/gu, "");
  const groups = [
    digits.slice(1, 4),
    digits.slice(4, 7),
    digits.slice(7, 9),
    digits.slice(9, 11),
  ];
  return [
    `плюс ${units[Number(digits[0])] ?? ""}`,
    ...groups.map(groupWords),
  ].join(", ");
}

